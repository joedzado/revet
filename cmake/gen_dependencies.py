#!/usr/bin/env python3
"""Parses revet.toml [build.dependencies] and emits build/generated/dependencies.cmake."""
import sys, re
from pathlib import Path
from codegen import tmpl, write_file

_DEP = tmpl("dependencies_dep.tmpl")

PROJ = Path(sys.argv[1])
TOML = PROJ / "revet.toml"
OUT  = PROJ / "build" / "generated" / "dependencies.cmake"
OUT.parent.mkdir(parents=True, exist_ok=True)

deps = {}  # key -> conan_ref (e.g., "fmt" -> "fmt/10.1.1")
if TOML.exists():
    toml = TOML.read_text()
    in_deps = False
    for line in toml.splitlines():
        stripped = line.strip()
        if re.match(r"\[build\.dependencies\]", stripped):
            in_deps = True
            continue
        if in_deps:
            if stripped.startswith("["):
                break
            # New format: key = "name/version"
            if m := re.match(r'["\']?([A-Za-z0-9_\-]+)["\']?\s*=\s*"([^"]+)"', stripped):
                deps[m.group(1)] = m.group(2)
            # Old/bare format: key = (no value or non-string)
            elif m := re.match(r'["\']?([A-Za-z0-9_\-]+)["\']?\s*=', stripped):
                deps[m.group(1)] = m.group(1)

cmake_lines = ["# Generated by gen_dependencies.py — do not edit"]
for key, conan_ref in deps.items():
    pkg_name = conan_ref.split("/")[0] if "/" in conan_ref else conan_ref
    cmake_lines.append(_DEP.substitute(pkg_name=pkg_name))

cmake_lines.append("")
write_file(OUT, "\n".join(cmake_lines))
