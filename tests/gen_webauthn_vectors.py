#!/usr/bin/env python3
"""Regenerates tests/webauthn_vectors.hpp: one WebAuthn registration and one login, built with the
`openssl` command line tool and a hand-written CBOR encoder, so the C++ verifier is checked against
bytes it did not produce. The private key in webauthn_vectors_key.pem is a throwaway used only here.

    python3 tests/gen_webauthn_vectors.py > tests/webauthn_vectors.hpp
"""
import base64, hashlib, json, os, subprocess, sys, tempfile

RP_ID = "app.example.com"
ORIGIN = "https://app.example.com"
CREDENTIAL_ID = bytes(range(1, 33))
AAGUID = bytes(16)


def head(major, n):
    if n < 24:
        return bytes([major << 5 | n])
    if n < 256:
        return bytes([major << 5 | 24, n])
    if n < 65536:
        return bytes([major << 5 | 25]) + n.to_bytes(2, "big")
    return bytes([major << 5 | 26]) + n.to_bytes(4, "big")


def uint(n): return head(0, n)
def nint(n): return head(1, -1 - n)
def bstr(b): return head(2, len(b)) + b
def tstr(s): return head(3, len(s.encode())) + s.encode()
def cmap(pairs): return head(5, len(pairs)) + b"".join(k + v for k, v in pairs)


def b64u(b): return base64.urlsafe_b64encode(b).rstrip(b"=").decode()


def run(args, data=None):
    return subprocess.run(args, input=data, capture_output=True, check=True).stdout


def main():
    d = tempfile.mkdtemp()
    key = os.path.join(d, "key.pem")
    # The key is generated once and committed, so regenerating gives vectors for the same credential.
    pem_path = os.path.join(os.path.dirname(__file__), "webauthn_vectors_key.pem")
    if not os.path.exists(pem_path):
        open(pem_path, "wb").write(run(["openssl", "ecparam", "-name", "prime256v1", "-genkey", "-noout"]))
    open(key, "wb").write(open(pem_path, "rb").read())
    spki = run(["openssl", "ec", "-in", key, "-pubout", "-outform", "DER"])
    point = spki[-65:]
    assert point[0] == 4
    x, y = point[1:33], point[33:]

    def sign(msg):
        p = os.path.join(d, "msg")
        open(p, "wb").write(msg)
        return run(["openssl", "dgst", "-sha256", "-sign", key, p])

    rp_hash = hashlib.sha256(RP_ID.encode()).digest()
    cose = cmap([(uint(1), uint(2)), (uint(3), nint(-7)), (nint(-1), uint(1)), (nint(-2), bstr(x)), (nint(-3), bstr(y))])

    reg_challenge = bytes(range(100, 132))
    reg_client = json.dumps({"type": "webauthn.create", "challenge": b64u(reg_challenge), "origin": ORIGIN, "crossOrigin": False},
                            separators=(",", ":")).encode()
    reg_auth = rp_hash + bytes([0x45]) + (0).to_bytes(4, "big") + AAGUID + len(CREDENTIAL_ID).to_bytes(2, "big") + CREDENTIAL_ID + cose
    reg_att = cmap([(tstr("fmt"), tstr("none")), (tstr("attStmt"), cmap([])), (tstr("authData"), bstr(reg_auth))])

    get_challenge = bytes(range(200, 232))
    get_client = json.dumps({"type": "webauthn.get", "challenge": b64u(get_challenge), "origin": ORIGIN, "crossOrigin": False},
                            separators=(",", ":")).encode()
    get_auth = rp_hash + bytes([0x05]) + (7).to_bytes(4, "big")
    get_sig = sign(get_auth + hashlib.sha256(get_client).digest())

    def arr(name, b):
        body = ",".join(f"0x{c:02x}" for c in b)
        return f"inline const std::string {name} = bytes({{{body}}});\n"

    out = ["// Generated by tests/gen_webauthn_vectors.py. Do not edit.\n", "#pragma once\n", "#include <initializer_list>\n", "#include <string>\n\n",
           "namespace webauthn_vectors {\n\n",
           "inline std::string bytes(std::initializer_list<unsigned char> b) { return std::string(b.begin(), b.end()); }\n\n",
           f'inline const std::string rp_id = "{RP_ID}";\n', f'inline const std::string origin = "{ORIGIN}";\n']
    out.append(arr("reg_challenge", reg_challenge))
    out.append(arr("reg_client_data_json", reg_client))
    out.append(arr("reg_attestation_object", reg_att))
    out.append(arr("credential_id", CREDENTIAL_ID))
    out.append(arr("public_key", point))
    out.append(arr("get_challenge", get_challenge))
    out.append(arr("get_client_data_json", get_client))
    out.append(arr("get_authenticator_data", get_auth))
    out.append(arr("get_signature", get_sig))
    out.append("inline constexpr unsigned get_sign_count = 7;\n\n} // namespace webauthn_vectors\n")
    sys.stdout.write("".join(out))


main()
