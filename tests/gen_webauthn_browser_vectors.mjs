// Regenerates tests/webauthn_browser_vectors.hpp: WebAuthn registrations and logins produced by a real
// Chromium (virtual authenticator over the DevTools protocol), so the C++ verifier is checked against bytes
// a browser's own implementation made. No dependencies; needs Node 22+ and a Chromium binary.
//
//   node tests/gen_webauthn_browser_vectors.mjs "/path/to/Chromium" > tests/webauthn_browser_vectors.hpp
import { spawn } from "node:child_process";
import { createServer } from "node:http";
import { mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const CHROME = process.argv[2];
const PAGE_PORT = 18095, DEBUG_PORT = 9334;
const ORIGIN = `http://localhost:${PAGE_PORT}`;
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

const page = createServer((_, res) => { res.setHeader("content-type", "text/html"); res.end("<!doctype html><title>vectors</title>"); }).listen(PAGE_PORT);
const chrome = spawn(CHROME, ["--headless=new", `--remote-debugging-port=${DEBUG_PORT}`, `--user-data-dir=${mkdtempSync(join(tmpdir(), "chrome-vec-"))}`,
  "--no-first-run", "--no-default-browser-check", "--disable-gpu", "about:blank"], { stdio: "ignore" });

let wsUrl;
for (let i = 0; i < 50 && !wsUrl; i++) { try { wsUrl = (await (await fetch(`http://127.0.0.1:${DEBUG_PORT}/json/version`)).json()).webSocketDebuggerUrl; } catch { await sleep(200); } }
const ws = new WebSocket(wsUrl);
await new Promise((r) => (ws.onopen = r));
let nextId = 1; const pending = new Map();
ws.onmessage = (m) => { const msg = JSON.parse(m.data); if (msg.id && pending.has(msg.id)) { const { res, rej } = pending.get(msg.id); pending.delete(msg.id); msg.error ? rej(new Error(JSON.stringify(msg.error))) : res(msg.result); } };
const send = (method, params = {}, sessionId) => new Promise((res, rej) => { const id = nextId++; pending.set(id, { res, rej }); ws.send(JSON.stringify({ id, method, params, ...(sessionId ? { sessionId } : {}) })); });
const { targetId } = await send("Target.createTarget", { url: ORIGIN + "/" });
const { sessionId } = await send("Target.attachToTarget", { targetId, flatten: true });
const cdp = (m, p) => send(m, p, sessionId);
await cdp("Page.enable"); await cdp("Runtime.enable"); await cdp("WebAuthn.enable");
await sleep(500);
const ev = async (expr) => { const r = await cdp("Runtime.evaluate", { expression: expr, awaitPromise: true, returnByValue: true }); if (r.exceptionDetails) throw new Error(JSON.stringify(r.exceptionDetails)); return r.result.value; };

const variants = [
  { name: "plain", attestation: "none", device: {} },
  { name: "direct", attestation: "direct", device: {} },
  { name: "synced", attestation: "none", device: { defaultBackupEligibility: true, defaultBackupState: true } },
];
const out = [];
for (const v of variants) {
  const { authenticatorId } = await cdp("WebAuthn.addVirtualAuthenticator", { options: {
    protocol: "ctap2", transport: "internal", hasResidentKey: true, hasUserVerification: true, isUserVerified: true,
    automaticPresenceSimulation: true, ...v.device } });
  const run = (body) => ev(`(async () => { const b = (x) => Array.from(new Uint8Array(x)); ${body} })()`);
  const reg = await run(`
    const challenge = new Uint8Array(32).map((_, i) => ${v.name.length} * 20 + i);
    const c = await navigator.credentials.create({ publicKey: { rp: { id: "localhost", name: "vectors" },
      user: { id: new Uint8Array(16).map((_, i) => 200 + i), name: "u", displayName: "u" }, challenge,
      pubKeyCredParams: [{ type: "public-key", alg: -7 }], attestation: "${v.attestation}",
      authenticatorSelection: { residentKey: "required", userVerification: "required" } } });
    return { challenge: b(challenge), cdj: b(c.response.clientDataJSON), att: b(c.response.attestationObject), id: b(c.rawId) };`);
  const gets = [];
  for (let k = 0; k < 2; k++) {
    gets.push(await run(`
      const challenge = new Uint8Array(32).map((_, i) => ${100 + k * 50} + i);
      const c = await navigator.credentials.get({ publicKey: { rpId: "localhost", challenge, userVerification: "required" } });
      return { challenge: b(challenge), cdj: b(c.response.clientDataJSON), ad: b(c.response.authenticatorData), sig: b(c.response.signature) };`));
  }
  const creds = (await cdp("WebAuthn.getCredentials", { authenticatorId })).credentials;
  out.push({ v, reg, gets, count: creds[0].signCount });
  await cdp("WebAuthn.removeVirtualAuthenticator", { authenticatorId });
}

const arr = (name, a) => `static inline const std::string ${name} = bytes({${a.map((x) => "0x" + x.toString(16).padStart(2, "0")).join(",")}});\n`;
let h = "// Generated by tests/gen_webauthn_browser_vectors.mjs from a real Chromium. Do not edit.\n#pragma once\n#include <initializer_list>\n#include <string>\n\nnamespace webauthn_browser_vectors {\n\n";
h += "inline std::string bytes(std::initializer_list<unsigned char> b) { return std::string(b.begin(), b.end()); }\n\n";
h += `inline const std::string rp_id = "localhost";\ninline const std::string origin = "${ORIGIN}";\n\n`;
for (const { v, reg, gets } of out) {
  h += `struct ${v.name} {\n`;
  h += arr("reg_challenge", reg.challenge) + arr("reg_client_data_json", reg.cdj) + arr("reg_attestation_object", reg.att) + arr("credential_id", reg.id);
  gets.forEach((g, k) => { h += arr(`get${k + 1}_challenge`, g.challenge) + arr(`get${k + 1}_client_data_json`, g.cdj) + arr(`get${k + 1}_authenticator_data`, g.ad) + arr(`get${k + 1}_signature`, g.sig); });
  h += `};\n\n`;
}
h += "} // namespace webauthn_browser_vectors\n";
process.stdout.write(h);
ws.close(); chrome.kill(); page.close();
setTimeout(() => process.exit(0), 100);
